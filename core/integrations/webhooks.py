"""Generic outbound webhook delivery (Week 51 task 2, plan §23): "outbound webhooks signed with
HMAC-SHA256 over the body and a timestamp to prevent replay."

Two delivery modes, because the two kinds of destination have different trust models:
- `deliver_signed` -- for a destination Bulwark expects to verify the signature (a custom receiver
  the operator wrote themselves). Signs `{timestamp}.{body}`, Stripe/Slack-style, so a captured
  request can't be replayed indefinitely; `verify_signature` is what that receiver's own code would
  call (also used by this project's own inbound webhook receivers where one is needed).
- `deliver_plain` -- for Slack and Discord's own incoming-webhook endpoints, which were never
  designed to check an HMAC signature from the sender at all (the webhook URL itself, generated by
  Slack/Discord, already acts as the shared secret). Signing a request they'll never verify would be
  security theater, not a real control.

Both validate the destination through `core.integrations.ssrf.validate_webhook_url` first and use
the same `core.ci.github.Transport`/`http_transport` convention (plain `urllib.request`, no new HTTP
dependency) every other outbound call in this codebase already follows.
"""

from __future__ import annotations

import hmac
import json
import time
from typing import Any

from core.ci.github import Transport, http_transport
from core.integrations.ssrf import validate_webhook_url
from core.netsafety import Resolver, default_resolver

HEADER_TIMESTAMP = "X-Bulwark-Timestamp"
HEADER_SIGNATURE = "X-Bulwark-Signature"
DEFAULT_MAX_AGE_SECONDS = 300


class WebhookDeliveryError(RuntimeError):
    """The destination failed SSRF validation, or responded with a non-2xx status."""


def sign(secret: str, timestamp: int, body: bytes) -> str:
    """`sha256=<hex>` over `{timestamp}.` followed by the raw body bytes -- the timestamp is part of
    the signed material, not just a sibling header, so an attacker can't swap in an old timestamp
    without invalidating the signature too."""
    mac = hmac.new(secret.encode(), f"{timestamp}.".encode() + body, "sha256")
    return f"sha256={mac.hexdigest()}"


def verify_signature(
    secret: str,
    timestamp: int,
    body: bytes,
    signature: str,
    *,
    max_age_seconds: int = DEFAULT_MAX_AGE_SECONDS,
    now: float | None = None,
) -> bool:
    """For a receiver of a Bulwark-signed webhook. Rejects a timestamp too far from now (either
    direction) before even computing the HMAC -- replay prevention is the timestamp *bound*, not the
    signature alone, since a captured request's signature stays valid forever otherwise."""
    current = now if now is not None else time.time()
    if abs(current - timestamp) > max_age_seconds:
        return False
    return hmac.compare_digest(signature, sign(secret, timestamp, body))


def _post(
    url: str, body: bytes, headers: dict[str, str], resolver: Resolver, transport: Transport
) -> None:
    validated = validate_webhook_url(url, resolver)
    status, _ = transport("POST", validated.url, headers, body)
    if not (200 <= status < 300):
        raise WebhookDeliveryError(f"{validated.host} responded with HTTP {status}")


def deliver_signed(
    url: str,
    payload: dict[str, Any],
    secret: str,
    *,
    resolver: Resolver = default_resolver,
    transport: Transport = http_transport,
    now: float | None = None,
) -> None:
    body = json.dumps(payload, sort_keys=True).encode()
    ts = int(now if now is not None else time.time())
    headers = {
        "Content-Type": "application/json",
        "User-Agent": "bulwark-webhooks",
        HEADER_TIMESTAMP: str(ts),
        HEADER_SIGNATURE: sign(secret, ts, body),
    }
    _post(url, body, headers, resolver, transport)


def deliver_plain(
    url: str,
    payload: dict[str, Any],
    *,
    resolver: Resolver = default_resolver,
    transport: Transport = http_transport,
) -> None:
    body = json.dumps(payload).encode()
    headers = {"Content-Type": "application/json", "User-Agent": "bulwark-webhooks"}
    _post(url, body, headers, resolver, transport)
