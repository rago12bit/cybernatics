"""The API's own connection to Temporal (plan §21.2): start a verified-fix workflow, signal a
human decision, read its status. A thin wrapper, not a second copy of the workflow's own logic --
everything here just calls into `temporalio.client.Client` using the same address/task-queue
convention `core/fixagent/worker.py` polls.
"""

from __future__ import annotations

import os
import uuid

from temporalio.client import Client, WorkflowHandle

from core.fixagent.limits import WorkflowLimits
from core.fixagent.worker import DEFAULT_ADDRESS, task_queue
from core.fixagent.workflow import VerifiedFixInput, VerifiedFixWorkflow

_client: Client | None = None


async def get_client() -> Client:
    """Cached per-process, the same shape `core.github_app`'s installation-token cache already
    uses: a fresh connection per request would be needless overhead, and Temporal's own client is
    safe to share across concurrent calls."""
    global _client
    if _client is None:
        address = os.environ.get("BULWARK_TEMPORAL_ADDRESS", DEFAULT_ADDRESS)
        _client = await Client.connect(address)
    return _client


def new_workflow_id(issue_id: str) -> str:
    """Generated by the caller (the API handler), not inside `start_verified_fix`, so the DB row
    (`core.fixagent.store.create_run`) can be created with the real workflow id BEFORE the workflow
    itself starts -- an activity looks the row up by workflow id from its very first write."""
    return f"fixagent-{issue_id}-{uuid.uuid4().hex[:8]}"


async def start_verified_fix(
    run_db_id: str,
    workflow_id: str,
    org_id: str,
    issue_id: str,
    finding: dict[str, object],
    clone_url: str,
    ref: str | None,
    originating_tool: str,
    baseline_fingerprints: list[str],
    repo_full_name: str | None,
    installation_id: str | None,
    run_tests: dict[str, object] | None,
    limits: WorkflowLimits | None = None,
) -> str:
    client = await get_client()
    inp = VerifiedFixInput(
        run_db_id=run_db_id,
        workflow_id=workflow_id,
        org_id=org_id,
        issue_id=issue_id,
        finding=finding,
        clone_url=clone_url,
        ref=ref,
        originating_tool=originating_tool,
        baseline_fingerprints=baseline_fingerprints,
        repo_full_name=repo_full_name,
        installation_id=installation_id,
        run_tests=run_tests,
        limits=(limits or WorkflowLimits.from_env()).__dict__,
    )
    await client.start_workflow(
        VerifiedFixWorkflow.run, inp, id=workflow_id, task_queue=task_queue()
    )
    return workflow_id


async def _handle(workflow_id: str) -> WorkflowHandle[VerifiedFixWorkflow, str]:
    client = await get_client()
    return client.get_workflow_handle(workflow_id)


async def approve(workflow_id: str) -> None:
    handle = await _handle(workflow_id)
    await handle.signal(VerifiedFixWorkflow.approve)


async def reject(workflow_id: str, reason: str = "") -> None:
    handle = await _handle(workflow_id)
    await handle.signal(VerifiedFixWorkflow.reject, reason)
